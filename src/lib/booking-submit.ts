import { BookingFormData, BookingSubmitResult } from "@/types/booking";

/**
 * Точка подключения реальной отправки бронирования.
 *
 * Сейчас данные никуда не отправляются — это осознанное решение,
 * пока владелец ресторана не выберет способ получения заявок.
 *
 * Когда способ будет выбран, здесь нужно добавить один из вариантов:
 *
 * 1) Telegram-бот — отправка через собственный API-роут Next.js
 *    (src/app/api/booking/route.ts), который вызывает Telegram Bot API.
 *
 * 2) Email — отправка через API-роут с сервисом рассылки
 *    (например, Resend, Nodemailer + SMTP).
 *
 * 3) CRM — POST-запрос на вебхук CRM-системы.
 *
 * 4) Собственный backend — POST-запрос на API ресторана.
 *
 * В любом из вариантов реальный запрос должен выполняться
 * через серверный API-роут Next.js, а не напрямую из браузера,
 * чтобы не раскрывать ключи/токены сторонних сервисов.
 */
export async function submitBooking(
  data: BookingFormData
): Promise<BookingSubmitResult> {
  // Временная заглушка: имитация отправки без реального запроса.
  await new Promise((resolve) => setTimeout(resolve, 600));

  console.info("[Бронирование] Данные формы (никуда не отправлены):", data);

  return {
    success: true,
    message:
      "Заявка принята локально. Реальная отправка ещё не подключена — обсудите с владельцем ресторана способ получения броней.",
  };
}